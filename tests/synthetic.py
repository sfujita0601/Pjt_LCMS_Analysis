"""テスト用の小さな模擬データ (LabSolutions のテキスト出力と同じ形式)。実データではない。

化合物:
    IS   内部標準。全試料に添加 (試料ごとに感度が違うと想定した値)
    AA1  1 / 25 / 50 の 3 点検量 (1 は 3 回測定)。S-1 の希釈なしは検量上限超過、S-2 は両方の希釈で上限超過
    AA2  25 の 1 点検量
    AA3  S-3 に数値として読めない値 (入力エラー) を入れる
試料: S-1 〜 S-4 (希釈なしと x10)、S-4 の希釈なしは 2 回測定 (再注入)
"""
HEADER = ("\tデータファイル名\tサンプルタイプ\t保持時間\t面積\t濃度\tS/N\t定量限界\t検出限界\t設定濃度\t正確さ%\t検量点\t誤差%"
          "\t分析日時\t統計計算\tサンプルID")

STD = [  # (ファイル, 設定濃度)
    ("20260101_1uM STD A__001.lcd", 1), ("20260101_1uM STD A__002.lcd", 1), ("20260101_1uM STD A__003.lcd", 1),
    ("20260101_25uM STD A__004.lcd", 25), ("20260101_50uM STD A__005.lcd", 50),
]
SAMPLES = [  # (ファイル, 時刻)
    ("20260101_S-1_1_010.lcd", "2026/01/01 10:00:00"), ("20260101_S-1 x10_1_011.lcd", "2026/01/01 10:10:00"),
    ("20260101_S-2_2_012.lcd", "2026/01/01 10:20:00"), ("20260101_S-2 x10_2_013.lcd", "2026/01/01 10:30:00"),
    ("20260101_S-3_3_014.lcd", "2026/01/01 10:40:00"), ("20260101_S-3 x10_3_015.lcd", "2026/01/01 10:50:00"),
    ("20260101_S-4_4_016.lcd", "2026/01/01 11:00:00"), ("20260101_S-4 x10_4_017.lcd", "2026/01/01 11:10:00"),
    ("20260101_S-4_4_018.lcd", "2026/01/01 11:20:00"),  # 再注入
]
# 測定液中濃度 (LabSolutions の出力。希釈倍率は未適用)
CONC = {
    "IS": {"S-1": 10.0, "S-1 x10": 5.0, "S-2": 20.0, "S-2 x10": 5.0, "S-3": 10.0, "S-3 x10": 5.0, "S-4": 10.0,
           "S-4 x10": 5.0, "S-4#2": 10.0},
    "AA1": {"S-1": 80.0, "S-1 x10": 8.2, "S-2": 900.0, "S-2 x10": 90.0, "S-3": 10.0, "S-3 x10": 1.1, "S-4": 20.0,
            "S-4 x10": 2.0, "S-4#2": 30.0},
    "AA2": {"S-1": 5.0, "S-1 x10": 0.5, "S-2": 6.0, "S-2 x10": 0.6, "S-3": 7.0, "S-3 x10": 0.7, "S-4": 8.0,
            "S-4 x10": 0.8, "S-4#2": 8.0},
    "AA3": {"S-1": 3.0, "S-1 x10": 0.3, "S-2": 3.0, "S-2 x10": 0.3, "S-3": "ERR", "S-3 x10": 0.3, "S-4": 3.0,
            "S-4 x10": 0.3, "S-4#2": 3.0},
}
LEVELS = {"IS": [1, 25, 50], "AA1": [1, 25, 50], "AA2": [25], "AA3": [1, 25, 50]}


def _key(file, i):
    name = file.split("_", 1)[1].rsplit("_", 2)[0]
    return name + ("#2" if i == 8 else "")


def make_text():
    lines = []
    for n, (cpd, values) in enumerate(CONC.items(), start=1):
        lines += [f"ID#\t{n}", f"Name\t{cpd}", HEADER]
        row = 1
        for f, lv in STD:
            used = lv in LEVELS[cpd]
            conc = lv * (1.05 if "002" in f else 0.97 if "003" in f else 1.0)
            vals = [f"{1.8:.3f}", f"{conc * 10000:.0f}", f"{conc:.3f}", "50", "0.30", "0.10", f"{lv}",
                    f"{100 * conc / lv:.1f}", "*" if used else "", "0", "2026/01/01 09:00:00", "*", ""]
            if not used:
                vals = ["-----"] * 6 + [f"{lv}", "-----", "", "-----", "2026/01/01 09:00:00", "*", ""]
            lines.append(f"{row}\t{f}\t標準(検量点)\t" + "\t".join(vals))
            row += 1
        for i, (f, t) in enumerate(SAMPLES):
            v = values[_key(f, i)]
            if isinstance(v, str):
                vals = ["1.8", "-----", v, "-----", "-----", "-----", "-----", "-----", "-----", "-----", t, "*", ""]
            else:
                vals = [f"{1.8:.3f}", f"{v * 10000:.0f}", f"{v:.3f}", "40", "0.30", "0.10", "-----", "-----", "-----",
                        "-----", t, "*", ""]
            lines.append(f"{row}\t{f}\t未知\t" + "\t".join(vals))
            row += 1
        lines.append("")
    return "\n".join(lines).encode("utf-8")
